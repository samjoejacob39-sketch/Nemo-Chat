# =============================================================================
# Nemo design-system reference audit
# -----------------------------------------------------------------------------
# Verifies that every self-contained HTML reference in design/references/:
#   1. carries the canonical NEMO-TOKENS block verbatim;
#   2. is strictly monochrome (no saturated hex / rgb / hsl colours);
#   3. exposes a working light/dark toggle via data-theme;
#   4. still contains its own markup, styles and scripts.
#
# Exit code 0 = clean, 1 = at least one violation.
# =============================================================================

[CmdletBinding()]
param(
    [string]$TokensPath,
    [string]$ReferencesPath,
    [int]$MaxChroma = 20
)

$ErrorActionPreference = 'Stop'

if (-not $TokensPath) { $TokensPath = Join-Path $PSScriptRoot 'nemo.tokens.css' }
if (-not $ReferencesPath) { $ReferencesPath = Join-Path $PSScriptRoot 'references' }

$startMarker = '<!-- NEMO-TOKENS:START -->'
$endMarker = '<!-- NEMO-TOKENS:END -->'
$violations = New-Object System.Collections.Generic.List[string]

function Add-Violation([string]$File, [int]$Line, [string]$Message) {
    $violations.Add(("{0}:{1}: {2}" -f $File, $Line, $Message))
}

function Get-LineNumber([string]$Text, [int]$Index) {
    if ($Index -le 0) { return 1 }
    return ([regex]::Matches($Text.Substring(0, $Index), "`n")).Count + 1
}

function Test-Chroma([int]$R, [int]$G, [int]$B) {
    $max = [Math]::Max($R, [Math]::Max($G, $B))
    $min = [Math]::Min($R, [Math]::Min($G, $B))
    return (($max - $min) -gt $MaxChroma)
}

if (-not (Test-Path -LiteralPath $TokensPath)) {
    throw "Canonical tokens not found: $TokensPath"
}
if (-not (Test-Path -LiteralPath $ReferencesPath)) {
    throw "References folder not found: $ReferencesPath"
}

$canonical = [System.IO.File]::ReadAllText((Resolve-Path -LiteralPath $TokensPath), [System.Text.Encoding]::UTF8).Trim()
$files = Get-ChildItem -LiteralPath $ReferencesPath -Filter '*.html' | Sort-Object Name

if ($files.Count -eq 0) {
    throw "No HTML references found in $ReferencesPath"
}

foreach ($file in $files) {
    $name = $file.Name
    $text = [System.IO.File]::ReadAllText($file.FullName, [System.Text.Encoding]::UTF8)

    # --- 1. Canonical token block ------------------------------------------
    $start = $text.IndexOf($startMarker, [System.StringComparison]::Ordinal)
    $end = $text.IndexOf($endMarker, [System.StringComparison]::Ordinal)
    if ($start -lt 0 -or $end -lt $start) {
        Add-Violation $name 1 'missing NEMO-TOKENS:START/END block'
    }
    else {
        $headEnd = $text.IndexOf('</head>', [System.StringComparison]::OrdinalIgnoreCase)
        if ($headEnd -lt 0) {
            Add-Violation $name 1 'missing </head>'
        }
        elseif ($start -gt $headEnd) {
            Add-Violation $name (Get-LineNumber $text $start) 'token block must live inside <head>'
        }

        $inner = $text.Substring($start + $startMarker.Length, $end - $start - $startMarker.Length)
        $styleOpen = $inner.IndexOf('<style id="nemo-tokens">', [System.StringComparison]::Ordinal)
        $styleClose = $inner.LastIndexOf('</style>', [System.StringComparison]::Ordinal)
        if ($styleOpen -lt 0 -or $styleClose -lt 0) {
            Add-Violation $name (Get-LineNumber $text $start) 'token block is not wrapped in <style id="nemo-tokens">'
        }
        else {
            $css = $inner.Substring($styleOpen + '<style id="nemo-tokens">'.Length, $styleClose - ($styleOpen + '<style id="nemo-tokens">'.Length))
            $css = ($css -replace '(?s)/\* Generated by design/sync-references\.ps1\. Do not edit inside this block\. \*/', '').Trim()
            if ($css -ne $canonical) {
                Add-Violation $name (Get-LineNumber $text $start) 'token block is out of sync with design/nemo.tokens.css'
            }
        }
    }

    # --- 2. Theme toggle ----------------------------------------------------
    if ($text -notmatch 'data-theme') {
        Add-Violation $name 1 'no data-theme light/dark mechanism'
    }
    $hasToggle = ($text -match 'dataset\.theme') -or
                 ($text -match "setAttribute\(\s*['""]data-theme['""]") -or
                 ($text -match "classList\.(toggle|add|remove)\(\s*['""]dark['""]")
    if (-not $hasToggle) {
        Add-Violation $name 1 'no scripted light/dark toggle'
    }
    if ($text -notmatch '(?i)(theme|appearance).{0,40}(btn|button|toggle)|(btn|button|toggle).{0,40}(theme|appearance)') {
        Add-Violation $name 1 'no visible theme control'
    }

    # --- 3. Self-contained structure ---------------------------------------
    if ($text -notmatch '(?is)<style[^>]*>.+?</style>') {
        Add-Violation $name 1 'missing own <style> block'
    }
    if ($text -notmatch '(?is)<script[^>]*>.+?</script>') {
        Add-Violation $name 1 'missing own <script> block'
    }
    if ($text -notmatch '(?is)<body[^>]*>.+</body>') {
        Add-Violation $name 1 'missing body markup'
    }

    # --- 4. Monochrome colours ---------------------------------------------
    foreach ($match in [regex]::Matches($text, '#([0-9A-Fa-f]{3,8})\b')) {
        $hex = $match.Groups[1].Value
        if ($hex.Length -eq 3) {
            $r = [Convert]::ToInt32(('{0}{0}' -f $hex[0]), 16)
            $g = [Convert]::ToInt32(('{0}{0}' -f $hex[1]), 16)
            $b = [Convert]::ToInt32(('{0}{0}' -f $hex[2]), 16)
        }
        elseif ($hex.Length -eq 4) {
            $r = [Convert]::ToInt32(('{0}{0}' -f $hex[0]), 16)
            $g = [Convert]::ToInt32(('{0}{0}' -f $hex[1]), 16)
            $b = [Convert]::ToInt32(('{0}{0}' -f $hex[2]), 16)
        }
        elseif ($hex.Length -eq 6 -or $hex.Length -eq 8) {
            $r = [Convert]::ToInt32($hex.Substring(0, 2), 16)
            $g = [Convert]::ToInt32($hex.Substring(2, 2), 16)
            $b = [Convert]::ToInt32($hex.Substring(4, 2), 16)
        }
        else {
            continue
        }
        if (Test-Chroma $r $g $b) {
            Add-Violation $name (Get-LineNumber $text $match.Index) ("saturated colour #$hex")
        }
    }

    foreach ($match in [regex]::Matches($text, 'rgba?\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})(?:\s*,\s*[\d.]+)?\s*\)')) {
        $r = [int]$match.Groups[1].Value
        $g = [int]$match.Groups[2].Value
        $b = [int]$match.Groups[3].Value
        if ((Test-Chroma $r $g $b)) {
            Add-Violation $name (Get-LineNumber $text $match.Index) ("saturated colour {0}" -f $match.Value)
        }
    }

    foreach ($match in [regex]::Matches($text, 'hsla?\(\s*([\d.]+)(?:deg)?\s*,\s*([\d.]+)%')) {
        if ([double]$match.Groups[2].Value -gt 10) {
            Add-Violation $name (Get-LineNumber $text $match.Index) ("saturated colour {0}" -f $match.Value)
        }
    }
}

Write-Host "Nemo reference audit"
Write-Host "  canonical: $TokensPath"
Write-Host "  references: $ReferencesPath"
Write-Host "  files: $($files.Count)"
Write-Host ""

if ($violations.Count -eq 0) {
    Write-Host 'PASS - every reference is monochrome, token-synced and theme-toggleable.' -ForegroundColor Green
    exit 0
}

Write-Host "FAIL - $($violations.Count) violation(s):" -ForegroundColor Red
foreach ($violation in $violations) {
    Write-Host "  $violation" -ForegroundColor Red
}
exit 1
