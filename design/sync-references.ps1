# =============================================================================
# Nemo design-system reference synchronizer
# -----------------------------------------------------------------------------
# Copies the canonical token block from design/nemo.tokens.css into every
# self-contained HTML reference in design/references/.
#
# The block is delimited by:
#   <!-- NEMO-TOKENS:START -->
#   <style id="nemo-tokens"> ... </style>
#   <!-- NEMO-TOKENS:END -->
#
# Only that block is ever touched. Markup, scripts and each reference's own
# light/dark toggle stay exactly as authored.
# =============================================================================

[CmdletBinding()]
param(
    [string]$TokensPath,
    [string]$ReferencesPath
)

$ErrorActionPreference = 'Stop'

if (-not $TokensPath) { $TokensPath = Join-Path $PSScriptRoot 'nemo.tokens.css' }
if (-not $ReferencesPath) { $ReferencesPath = Join-Path $PSScriptRoot 'references' }

if (-not (Test-Path -LiteralPath $TokensPath)) {
    throw "Canonical tokens not found: $TokensPath"
}
if (-not (Test-Path -LiteralPath $ReferencesPath)) {
    throw "References folder not found: $ReferencesPath"
}

$tokens = [System.IO.File]::ReadAllText((Resolve-Path -LiteralPath $TokensPath), [System.Text.Encoding]::UTF8).Trim()
if ($tokens -match '</style') {
    throw 'The token source must not contain a closing style tag.'
}

$startMarker = '<!-- NEMO-TOKENS:START -->'
$endMarker = '<!-- NEMO-TOKENS:END -->'
$block = @(
    $startMarker
    '<style id="nemo-tokens">'
    '/* Generated by design/sync-references.ps1. Do not edit inside this block. */'
    $tokens
    '</style>'
    $endMarker
) -join "`r`n"

$utf8 = New-Object System.Text.UTF8Encoding($false)
$files = Get-ChildItem -LiteralPath $ReferencesPath -Filter '*.html' | Sort-Object Name

if ($files.Count -eq 0) {
    throw "No HTML references found in $ReferencesPath"
}

foreach ($file in $files) {
    $text = [System.IO.File]::ReadAllText($file.FullName, [System.Text.Encoding]::UTF8)
    $start = $text.IndexOf($startMarker, [System.StringComparison]::Ordinal)
    $end = $text.IndexOf($endMarker, [System.StringComparison]::Ordinal)

    if ($start -ge 0 -and $end -gt $start) {
        $endOfBlock = $end + $endMarker.Length
        $text = $text.Substring(0, $start) + $block + $text.Substring($endOfBlock)
        $state = 'updated'
    }
    else {
        $headEnd = $text.IndexOf('</head>', [System.StringComparison]::OrdinalIgnoreCase)
        if ($headEnd -lt 0) {
            throw "$($file.Name): no closing </head> tag found"
        }
        $text = $text.Substring(0, $headEnd) + $block + "`r`n" + $text.Substring($headEnd)
        $state = 'inserted'
    }

    [System.IO.File]::WriteAllText($file.FullName, $text, $utf8)
    Write-Host ("{0,-46} {1}" -f $file.Name, $state)
}

Write-Host ''
Write-Host "Synchronized $($files.Count) reference(s) from $TokensPath."
